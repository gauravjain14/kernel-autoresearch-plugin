"""Canaries: known-cheating kernels the evaluator must reject before a run may start.

Generic canaries are templates instantiated against the task's own reference, inputs and shapes (a real cheater reads
those files too). A task can add its own in task.toml `canaries` (full candidate files, expected rejected by check).
"""
import base64
import os
import random

TEMPLATES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "canary_templates")

# name -> the stage that must reject it
GENERIC = {
    "cache_by_ptr": "check",
    "scored_only": "check",
    "low_precision": "check",
    "graph_skip": "check",
    "side_stream": "check",
    "stateful": "check",
    "mutate_input": "check",
    "timer_tamper": "smoke",
    "tf32_flip": "smoke",
    "blob": "lint",
    "shared_output": "stress",
}

HEADER = '''# Generated by kar for task {name!r}.
import importlib
import sys

import torch

_ROOT = {root!r}
if _ROOT not in sys.path:
    sys.path.append(_ROOT)


def _attr(spec):
    f, _, a = spec.partition(":")
    return getattr(importlib.import_module(f[:-3].replace("/", ".")), a)


_ref = _attr({reference!r})
_make = _attr({inputs!r})
_scored = _attr({shapes!r})

'''


def header(task):
    return HEADER.format(name=task.name, root=task.root, reference=task.reference, inputs=task.inputs,
                         shapes=task.shapes)


def reference_candidate(task, out_dir):
    """The task's reference wrapped as a candidate (it must pass its own check)."""
    os.makedirs(out_dir, exist_ok=True)
    p = os.path.join(out_dir, "reference_kernel.py")
    with open(p, "w") as f:
        f.write(header(task) + f"{task.entry} = _ref\n")
    return p


def materialize(task, out_dir):
    """Write every canary for this task; returns [(label, path, stage_that_must_reject)]."""
    os.makedirs(out_dir, exist_ok=True)
    out = []
    for name, stage in GENERIC.items():
        with open(os.path.join(TEMPLATES, name + ".py.in")) as f:
            body = f.read()
        if "@BLOB@" in body:
            body = body.replace("@BLOB@", base64.b64encode(random.Random(0).randbytes(900)).decode())
        body = body.replace("def kernel_fn(", f"def {task.entry}(")
        p = os.path.join(out_dir, f"canary_{name}.py")
        with open(p, "w") as f:
            f.write(header(task) + body)
        out.append((f"canary:{name}", p, stage))
    for rel in task.canaries:
        out.append((f"canary:{os.path.splitext(os.path.basename(rel))[0]}", task.path(rel), "check"))
    return out
